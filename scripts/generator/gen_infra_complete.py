import os

def write_file(filepath, content):
    dir_name = os.path.dirname(filepath)
    if dir_name:
        os.makedirs(dir_name, exist_ok=True)
    clean = content.strip() + "\n"
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(clean)
    lines = len(clean.splitlines())
    return lines

